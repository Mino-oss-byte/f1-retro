// Converts a TUM racetrack-database track + raceline CSV into the game's track data file.
// Source: https://github.com/TUMFTM/racetrack-database (LGPL-3.0)
//
// node scripts/import-track.js --track raw/X.csv --line raw/X_line.csv --out src/data/tracks/x.js
//        --id x --name "X" --direction clockwise --theme overcast [--elevation key]
//
// Elevation is not in the TUM data; `--elevation key` applies a hand-written profile
// from scripts/elevation-profiles.js.
import fs from 'node:fs';
import profiles from './elevation-profiles.js';

const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
for (const k of ['track', 'line', 'out', 'id', 'name', 'direction', 'theme']) {
  if (!args[k]) { console.error(`missing --${k}`); process.exit(1); }
}

const rows = (file) => fs.readFileSync(file, 'utf8')
  .split(/\r?\n/)
  .filter((l) => l.trim() && !l.startsWith('#'))
  .map((l) => l.split(',').map(Number));

const r2 = (v) => Math.round(v * 100) / 100;

// CSV y points "up" on a map; the game uses z toward the viewer, so z = -y keeps the track's orientation.
const track = rows(args.track);
const n = track.length;
const centerline = track.map(([x, y]) => [r2(x), r2(-y)]);

// cosine-interpolated elevation from [index, metres] keys (closed loop)
function elevationFrom(keys) {
  const out = new Array(n).fill(0);
  for (let i = 0; i < n; i++) {
    let a = keys[keys.length - 1], b = keys[0];
    for (let k = 0; k < keys.length - 1; k++) {
      if (i >= keys[k][0] && i <= keys[k + 1][0]) { a = keys[k]; b = keys[k + 1]; break; }
    }
    const t = (i - a[0]) / Math.max(1, b[0] - a[0]);
    out[i] = r2(a[1] + (b[1] - a[1]) * (1 - Math.cos(Math.PI * t)) / 2);
  }
  return out;
}

// how far the start/finish straight extends behind and ahead of index 0 -> pit lane placement
function turnAt(i) {
  const h = (k) => {
    const p = centerline[(k + n) % n], q = centerline[(k + 1 + n) % n];
    return Math.atan2(q[0] - p[0], q[1] - p[1]);
  };
  let d = Math.abs(h(i + 1) - h(i));
  if (d > Math.PI) d = Math.PI * 2 - d;
  return d;
}
const smooth = (i) => (turnAt(i - 1) + turnAt(i) + turnAt(i + 1)) / 3;
let back = 0; while (back < 150 && smooth(-back - 1) < 0.02) back++;
let fwd = 0; while (fwd < 250 && smooth(fwd) < 0.02) fwd++;
const before = Math.min(back - 2, 40);
const after = Math.min(fwd - 4, 70);
const pit = { start: (n - before) % n, length: before + after };

const data = {
  id: args.id,
  name: args.name,
  direction: args.direction,
  theme: args.theme,
  startIndex: 0,
  pit,
  centerline,
  widthRight: track.map((r) => r2(r[2])),
  widthLeft: track.map((r) => r2(r[3])),
  elevation: args.elevation ? elevationFrom(profiles[args.elevation]) : new Array(n).fill(0),
  racingLine: rows(args.line).map(([x, y]) => [r2(x), r2(-y)]),
};

fs.writeFileSync(args.out, `// Generated by scripts/import-track.js from the TUM racetrack database (LGPL-3.0). Do not edit by hand.\nexport default ${JSON.stringify(data)};\n`);
console.log(`wrote ${args.out}: ${n} points, pit lane ${pit.length} points from ${pit.start}`);
